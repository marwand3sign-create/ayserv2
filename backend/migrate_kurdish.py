async def main():
    c = AsyncIOMotorClient(os.environ["MONGO_URL"])
    db = c[os.environ["DB_NAME"]]

    svc_updated = 0
    for sid, data in SERVICES_KU.items():
        doc = await db.services.find_one({"id": sid})
        if not doc:
            continue
        desc = {**(doc.get("desc") or {}), "ku": data["desc"]}
        benefit = {**(doc.get("benefit") or {}), "ku": data["benefit"]}
        await db.services.update_one(
            {"id": sid},
            {"$set": {"ku": data["ku"], "desc": desc, "benefit": benefit}},
        )
        svc_updated += 1

    faq_updated = 0
    for en_q, data in FAQ_KU.items():
        doc = await db.faq.find_one({"q.en": en_q})
        if not doc:
            continue
        q = {**(doc.get("q") or {}), "ku": data["q"]}
        a = {**(doc.get("a") or {}), "ku": data["a"]}
        await db.faq.update_one({"_id": doc["_id"]}, {"$set": {"q": q, "a": a}})
        faq_updated += 1

    await db.settings.update_one(
        {"key": "site"},
        {"$set": {"cityKu": "عێراق - هەولێر - پیشەسازیی باکوور - گەراجی ٩٨"}},
    )

    print(f"services updated: {svc_updated}, faq updated: {faq_updated}")


asyncio.run(main())
